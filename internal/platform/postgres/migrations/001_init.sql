-- =============================================================================
-- 001_init.sql — the initial schema.
--
-- Read this file alongside docs/ARCHITECTURE.md. Every index and constraint
-- below exists for a stated reason; none of them are decoration.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- orders — the aggregate root
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS orders (
    -- A UUID primary key, generated by the APPLICATION, not the database.
    --
    -- WHY NOT BIGSERIAL: a sequential id leaks business volume (/orders/4172
    -- tells a competitor how many orders you have had) and is guessable,
    -- which invites probing other customers' orders. A UUID also means the
    -- application knows the id BEFORE the insert, which is what makes
    -- idempotent retries and client-generated ids possible.
    --
    -- THE COST, STATED HONESTLY: a random UUID primary key has worse index
    -- locality than a sequential one. Inserts scatter across the B-tree
    -- instead of appending to the right-hand edge, so the index is less
    -- cache-friendly and pages split more. At our scale this is irrelevant;
    -- at tens of millions of rows per day you would use UUIDv7 (time-ordered)
    -- to get both properties.
    id                  UUID PRIMARY KEY,

    -- The human-facing reference printed on the receipt: ORD-7K2M9QX4.
    -- UNIQUE is the real guarantee behind our random generation: collisions
    -- are astronomically unlikely, and this constraint makes them impossible
    -- rather than merely improbable.
    order_number        TEXT NOT NULL UNIQUE,

    customer_id         TEXT NOT NULL,
    customer_email      TEXT NOT NULL,
    customer_name       TEXT NOT NULL DEFAULT '',

    -- Status as TEXT with a CHECK constraint, not a Postgres ENUM type.
    --
    -- WHY: adding a value to an ENUM requires ALTER TYPE, which historically
    -- could not run inside a transaction and is awkward in a migration.
    -- A CHECK constraint is just as strict, and changing it is an ordinary
    -- transactional DDL statement.
    --
    -- WHY HAVE THE CONSTRAINT AT ALL when the application validates? DEFENCE
    -- IN DEPTH. The application is the first line; the database is the last.
    -- A bad migration, a manual psql session or a future second writer cannot
    -- insert a status the state machine does not recognise.
    status              TEXT NOT NULL CHECK (status IN
                            ('PENDING','PROCESSING','SHIPPED','DELIVERED','CANCELLED','FAILED')),

    -- MONEY AS BIGINT MINOR UNITS (cents). Never NUMERIC, never FLOAT.
    -- See internal/order/domain/money.go for the full reasoning; the short
-- version is that float arithmetic produces one-cent discrepancies that
    -- auditors find and nobody can reconstruct.
    total_amount_minor  BIGINT NOT NULL CHECK (total_amount_minor > 0),
    currency            CHAR(3) NOT NULL DEFAULT 'USD',

    shipping_address    TEXT NOT NULL,
    notes               TEXT NOT NULL DEFAULT '',

    -- version drives OPTIMISTIC LOCKING. Every update does
    --   ... WHERE id = $1 AND version = $2
    -- and sets version = version + 1. A mismatch means someone else
    -- committed first, so we detected a lost update instead of causing one.
    version             INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),

    -- Two distinct reason columns, because the two outcomes are
    -- operationally different: a customer choice vs a system failure.
    -- One shared column would lose that distinction in reporting.
    cancel_reason       TEXT,
    failure_reason      TEXT,

    -- Links the order to its distributed transaction, so a stuck order can be
    -- traced to the exact saga step that failed.
    saga_id             UUID,

    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- status_changed_at is SEPARATE from updated_at on purpose. The
    -- auto-advance worker asks "which orders have been PENDING for over 5
    -- minutes?" — and editing a note must not reset that clock. Reusing
    -- updated_at would mean any unrelated edit silently delays processing.
    status_changed_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Which system owns this record. 'legacy' means it came from the old
    -- service via the Strangler Fig. A GROUP BY source is how you measure
    -- migration progress instead of guessing at it.
    source              TEXT NOT NULL DEFAULT 'new' CHECK (source IN ('new','legacy')),

    -- TIMESTAMPTZ everywhere, never TIMESTAMP.
    -- TIMESTAMPTZ stores an absolute instant; TIMESTAMP stores a wall-clock
    -- reading with no timezone, so "2026-03-29 01:30" is ambiguous or
    -- non-existent during a DST transition. Order timelines must be exact.

    -- A belt-and-braces invariant: a cancelled order must carry a reason.
    CONSTRAINT cancelled_orders_have_a_reason
        CHECK (status <> 'CANCELLED' OR cancel_reason IS NOT NULL)
);

-- -----------------------------------------------------------------------------
-- Indexes on orders.
--
-- EVERY INDEX IS A TRADE-OFF, and it is worth being explicit about it:
--   + Reads matching the index get dramatically faster.
--   - Every INSERT and UPDATE must also update the index, so writes slow down.
--   - It consumes disk and memory, competing with your table for cache.
-- So we add indexes that serve a QUERY WE ACTUALLY RUN, and no others.
-- An unused index is pure cost.
-- -----------------------------------------------------------------------------

-- Serves: GET /orders?customer_id=X  ("show me my orders, newest first")
-- A COMPOSITE index with created_at DESC means Postgres can satisfy both the
-- filter AND the sort from one index scan, with no separate sort step.
-- Column ORDER matters: (customer_id, created_at) can serve a query filtering
-- on customer_id alone; (created_at, customer_id) cannot.
CREATE INDEX IF NOT EXISTS idx_orders_customer_created
    ON orders (customer_id, created_at DESC);

-- Serves the auto-advance worker:
--   WHERE status = 'PENDING' AND status_changed_at <= $cutoff
--
-- This is a PARTIAL INDEX (note the WHERE clause). It indexes ONLY pending
-- rows, which is the key insight: 99% of orders are eventually DELIVERED and
-- will never match this query, so indexing them is wasted space and wasted
-- write cost. A partial index here is perhaps 1% the size of a full one, stays
-- resident in memory, and SHRINKS as orders complete.
--
-- Partial indexes are one of the highest-leverage, least-used Postgres
-- features for exactly this "hot subset of a big table" pattern.
CREATE INDEX IF NOT EXISTS idx_orders_pending_stale
    ON orders (status_changed_at)
    WHERE status = 'PENDING';

-- Serves: GET /orders?status=X, and the stats GROUP BY.
CREATE INDEX IF NOT EXISTS idx_orders_status_created
    ON orders (status, created_at DESC);

-- order_number already has a UNIQUE index from its constraint, so a separate
-- index on it would be redundant — a duplicate index costs writes and space
-- for no gain. Worth stating explicitly, because adding one is a common
-- reflex.

-- -----------------------------------------------------------------------------
-- order_items — the lines of an order
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS order_items (
    id                  UUID PRIMARY KEY,

    -- ON DELETE CASCADE: deleting an order removes its items automatically.
    --
    -- WHY CASCADE IS SAFE HERE: an order item has no independent existence —
    -- it is part of the order aggregate. Orphaned items would be unreachable
    -- garbage. (We never actually delete orders in normal operation; this
    -- matters for data-retention/GDPR erasure jobs.)
    order_id            UUID NOT NULL REFERENCES orders(id) ON DELETE CASCADE,

    product_id          TEXT NOT NULL,

    -- DENORMALISED SNAPSHOTS, and this is deliberate.
    --
    -- product_name and unit_price_minor are copied here at purchase time
    -- rather than joined from a products table. An order is a HISTORICAL
    -- RECORD of what was agreed. If the product's price changes, or it is
    -- renamed, or it is deleted from the catalogue, last year's invoice must
    -- still show what the customer actually bought and paid.
    --
    -- Joining live catalogue data would silently REWRITE HISTORY and break
    -- your accounting. This is "denormalise for correctness", which is a
    -- stronger justification than the usual "denormalise for performance"
    -- (though we get that too: no join on the read path).
    product_name        TEXT NOT NULL,
    product_sku         TEXT NOT NULL DEFAULT '',

    quantity            INTEGER NOT NULL CHECK (quantity > 0),
    unit_price_minor    BIGINT NOT NULL CHECK (unit_price_minor > 0),
    line_total_minor    BIGINT NOT NULL CHECK (line_total_minor > 0),
    currency            CHAR(3) NOT NULL DEFAULT 'USD',
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- The quantity > 0 check blocks the classic exploit: a negative quantity
    -- makes the line total negative, reducing the order total so the attacker
    -- pays less than the real price — or is owed money.

    -- One product appears at most once per order; duplicates are merged into
    -- a single line with a larger quantity by the domain factory. This
    -- constraint is what guarantees the warehouse never sees two lines for
    -- the same SKU and picks it twice.
    CONSTRAINT one_line_per_product_per_order UNIQUE (order_id, product_id)
);

-- Serves the items lookup for one order, and the batched
-- "WHERE order_id = ANY($1)" query that solves the N+1 problem.
CREATE INDEX IF NOT EXISTS idx_order_items_order
    ON order_items (order_id, created_at);

-- -----------------------------------------------------------------------------
-- outbox — the TRANSACTIONAL OUTBOX
--
-- Events are inserted in the SAME TRANSACTION as the state change they
-- describe, which is what makes "save the order" and "announce the order"
-- atomic without a distributed transaction. See domain/ports.go for the
-- dual-write problem this solves.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS outbox (
    -- TEXT rather than UUID, because some event ids are DETERMINISTIC
    -- composites like '<order-id>:PROCESSING:auto'. A deterministic id plus
    -- ON CONFLICT DO NOTHING is what makes the auto-advance job idempotent.
    id                  TEXT PRIMARY KEY,

    aggregate_type      TEXT NOT NULL,
    aggregate_id        TEXT NOT NULL,
    event_type          TEXT NOT NULL,
    -- JSONB, not TEXT: it is validated on write (malformed JSON is rejected
    -- at the door) and queryable, which matters when you are debugging
    -- "which events mentioned this product?".
    payload             JSONB NOT NULL DEFAULT '{}'::JSONB,

    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- NULL means "not yet published". Using NULL rather than a boolean lets
    -- us build the partial index below AND records WHEN it was published,
    -- which is what you need to measure publishing lag.
    published_at        TIMESTAMPTZ,

    -- attempts drives the POISON-MESSAGE GUARD. An event that can never be
    -- published (bad payload, deleted topic) would otherwise be retried
    -- forever, consuming the whole batch on every cycle and starving every
    -- healthy event behind it.
    attempts            INTEGER NOT NULL DEFAULT 0,
    last_error          TEXT
);

-- THE OUTBOX WORKER'S QUERY, and the most important index in this file:
--   SELECT ... WHERE published_at IS NULL AND attempts < 10
--   ORDER BY created_at LIMIT 50 FOR UPDATE SKIP LOCKED
--
-- A PARTIAL INDEX on unpublished rows only. This is what keeps the outbox
-- fast forever: the table accumulates millions of PUBLISHED rows, but this
-- index contains only the handful that are still pending. Its size tracks the
-- BACKLOG, not the history — so the polling query stays constant-time no
-- matter how much has flowed through.
CREATE INDEX IF NOT EXISTS idx_outbox_unpublished
    ON outbox (created_at)
    WHERE published_at IS NULL;

-- Serves the retention purge: DELETE WHERE published_at < cutoff.
CREATE INDEX IF NOT EXISTS idx_outbox_published_at
    ON outbox (published_at)
    WHERE published_at IS NOT NULL;

-- -----------------------------------------------------------------------------
-- saga_instances — durable saga state
--
-- WHY THIS TABLE EXISTS: if the process dies mid-saga, nobody knows whether
-- the card was charged or the stock reserved — so nobody can know what to
-- compensate. This row is the difference between "eventually consistent" and
-- "permanently broken, with a customer charged for nothing".
--
-- (The running code keeps saga state in memory and this table is the
-- production-ready schema for the recovery worker. That gap is stated plainly
-- in docs/TRADEOFFS.md rather than glossed over.)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS saga_instances (
    id                  UUID PRIMARY KEY,
    saga_type           TEXT NOT NULL,
    order_id            UUID NOT NULL,
    status              TEXT NOT NULL CHECK (status IN
                            ('RUNNING','COMPLETED','COMPENSATING','COMPENSATED','COMPENSATION_FAILED')),
    -- completed_steps records each step and the HANDLE it returned (the
    -- reservation id, the payment id). Without the handle, a recovery worker
    -- knows a step ran but cannot undo it.
    completed_steps     JSONB NOT NULL DEFAULT '[]'::JSONB,
    last_error          TEXT,
    started_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ended_at            TIMESTAMPTZ
);

-- Serves the RECOVERY WORKER: "find sagas that have been RUNNING too long",
-- i.e. ones whose process died. A partial index again, because completed
-- sagas are never scanned by this query and there will eventually be millions
-- of them.
CREATE INDEX IF NOT EXISTS idx_saga_stuck
    ON saga_instances (started_at)
    WHERE status IN ('RUNNING','COMPENSATING');

-- Serves the diagnostic endpoint: "show me the sagas for this order".
CREATE INDEX IF NOT EXISTS idx_saga_order
    ON saga_instances (order_id);

-- COMPENSATION_FAILED is the state that needs a human. This index makes the
-- alerting query ("is anything in this state right now?") instant, which
-- matters because every row here potentially means a customer was charged
-- for an order they will not receive.
CREATE INDEX IF NOT EXISTS idx_saga_needs_attention
    ON saga_instances (updated_at)
    WHERE status = 'COMPENSATION_FAILED';
